"""Generates firmware/main/sounds_pcm.c: short PCM sounds of the pet.

The sounds are synthesised here (sine tones with short fades), so they carry
no third-party licence. Run from the repository root after changing them:

    python firmware/tools/gen_sounds.py
"""

import math
from pathlib import Path

RATE = 16000
PEAK = 0.8  # of full scale; the firmware scales again by the configured volume
FADE_MS = 5

# name -> list of (frequency Hz or 0 for silence, duration ms)
SOUNDS = {
    "touch": [(1200, 40)],
    "confirm": [(880, 80), (1320, 80)],
    "alert": [(1000, 100), (0, 60), (1000, 100), (0, 60), (1000, 100)],
    "study_done": [(1320, 150), (990, 150), (660, 250)],
}


def segment(freq, ms):
    n = RATE * ms // 1000
    fade = RATE * FADE_MS // 1000
    out = []
    for i in range(n):
        if freq == 0:
            out.append(0)
            continue
        env = min(1.0, i / fade, (n - 1 - i) / fade)
        out.append(round(32767 * PEAK * env * math.sin(2 * math.pi * freq * i / RATE)))
    return out


def main():
    lines = [
        "// Generated by firmware/tools/gen_sounds.py. Do not edit by hand.",
        "// 16 kHz, mono, signed 16-bit PCM. Synthesised tones, no third-party content.",
        "",
        '#include "sounds_pcm.h"',
        "",
    ]
    table = []
    for name, parts in SOUNDS.items():
        samples = [s for f, ms in parts for s in segment(f, ms)]
        lines.append(f"static const int16_t pcm_{name}[{len(samples)}] = {{")
        for i in range(0, len(samples), 12):
            lines.append("    " + ", ".join(str(s) for s in samples[i:i + 12]) + ",")
        lines.append("};")
        lines.append("")
        table.append(f"    [SOUND_{name.upper()}] = {{pcm_{name}, {len(samples)}}},")
    lines.append("const sound_pcm_t sound_pcm_table[SOUND_COUNT] = {")
    lines += table
    lines.append("};")
    out = Path(__file__).resolve().parent.parent / "main" / "sounds_pcm.c"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
